#!/usr/bin/env python3 -I
"""dataset_audit.py — Comprehensive dataset audit for Phase 1.

Produces:
  reports/dataset_audit.md   — class distributions, session mapping, feature variance
  reports/dataset_audit.json — machine-readable audit results

Usage:
  cd iot_digital_twin_working
  python3 -I dataset_audit.py --dataset data/dataset_v3.jsonl --out-dir reports/
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import json, argparse, math
from collections import Counter, defaultdict
import numpy as np
from common import FEATURE_ORDER_V2, FEATURE_ORDER_V1, SYSCALL_FEATURES, ENERGY_FEATURES, load_records, to_vector

def wilson_ci(k, n, z=1.96):
    """Wilson score 95% CI for proportion k/n."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z*z/n
    centre = (p + z*z/(2*n)) / denom
    spread = z * math.sqrt((p*(1-p) + z*z/(4*n)) / n) / denom
    return (max(0.0, centre - spread), min(1.0, centre + spread))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="data/dataset_v3.jsonl")
    ap.add_argument("--out-dir", default="reports")
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    records = load_records(args.dataset)
    n_total = len(records)

    # --- Class distribution ---
    labels = [r.get("label", "") for r in records]
    classes = [r.get("attack_class", "") for r in records]
    run_ids = [str(r.get("run_id", "NONE")) for r in records]

    label_counts = Counter(labels)
    class_counts = Counter(classes)

    # --- Session/run_id mapping ---
    run_id_info = defaultdict(lambda: {"label": set(), "attack_class": set(), "count": 0})
    for r in records:
        rid = str(r.get("run_id", "NONE"))
        run_id_info[rid]["label"].add(r.get("label", ""))
        run_id_info[rid]["attack_class"].add(r.get("attack_class", ""))
        run_id_info[rid]["count"] += 1

    # --- Eligible for supervised ---
    supervised_idx = [i for i, r in enumerate(records)
                      if r.get("label") in ("benign", "malware")]
    n_supervised = len(supervised_idx)

    # --- Feature variance analysis ---
    vectors = np.array([to_vector(r, FEATURE_ORDER_V2) for r in records
                        if r.get("label") in ("benign", "malware")])
    feature_names = list(FEATURE_ORDER_V2)
    variances = np.var(vectors, axis=0)
    zero_var = [(feature_names[i], float(vectors[0, i])) for i in range(len(feature_names))
                if variances[i] == 0.0]
    n_effective = len(feature_names) - len(zero_var)

    # --- Per-feature statistics ---
    feature_stats = []
    for i, fname in enumerate(feature_names):
        col = vectors[:, i]
        feature_stats.append({
            "feature": fname,
            "monitor": "syscall" if fname.startswith("sys_") else "energy" if fname.startswith("energy_") else "network",
            "mean": float(np.mean(col)),
            "std": float(np.std(col)),
            "min": float(np.min(col)),
            "max": float(np.max(col)),
            "variance": float(variances[i]),
            "zero_variance": bool(variances[i] == 0.0),
        })

    # --- Build report ---
    md = []
    md.append("# Dataset Audit Report")
    md.append(f"\n**Generated by**: `dataset_audit.py`")
    md.append(f"**Dataset**: `{args.dataset}`")
    md.append(f"**Total windows**: {n_total}")
    md.append(f"**Eligible for supervised training/evaluation**: {n_supervised}")
    md.append(f"**Status**: PRELIMINARY (single-session attack data)\n")

    md.append("## 1. Label Distribution\n")
    md.append("| Label | Count | % of total |")
    md.append("|-------|-------|-----------|")
    for lbl in sorted(label_counts.keys()):
        c = label_counts[lbl]
        md.append(f"| {lbl or '(empty)'} | {c} | {100*c/n_total:.1f}% |")

    md.append("\n## 2. Attack Class Distribution (supervised only)\n")
    md.append("| Class | Count | % of supervised |")
    md.append("|-------|-------|----------------|")
    sup_classes = Counter()
    for i in supervised_idx:
        r = records[i]
        cls = r.get("attack_class", "") or "benign"
        sup_classes[cls] += 1
    for cls in sorted(sup_classes.keys()):
        c = sup_classes[cls]
        md.append(f"| {cls} | {c} | {100*c/n_supervised:.1f}% |")

    md.append("\n## 3. Run-ID Summary\n")
    md.append("| run_id | windows | labels | attack_classes |")
    md.append("|--------|---------|--------|---------------|")
    for rid in sorted(run_id_info.keys(), key=lambda x: (x == "NONE", x)):
        info = run_id_info[rid]
        md.append(f"| {rid} | {info['count']} | {', '.join(sorted(info['label']))} | {', '.join(sorted(info['attack_class'])) or '-'} |")

    md.append(f"\n**Total unique run_ids**: {len(run_id_info)}")

    md.append("\n## 4. Feature Variance Analysis\n")
    md.append(f"**Total features**: {len(feature_names)}")
    md.append(f"**Zero-variance features**: {len(zero_var)}")
    md.append(f"**Effective features**: {n_effective}\n")

    if zero_var:
        md.append("### Zero-variance features\n")
        md.append("| Feature | Monitor | Constant value |")
        md.append("|---------|---------|---------------|")
        for fname, val in zero_var:
            mon = "syscall" if fname.startswith("sys_") else "energy" if fname.startswith("energy_") else "network"
            md.append(f"| `{fname}` | {mon} | {val} |")

    md.append("\n### Feature statistics (supervised windows only)\n")
    md.append("| Feature | Monitor | Mean | Std | Min | Max | Zero-var |")
    md.append("|---------|---------|------|-----|-----|-----|----------|")
    for fs in feature_stats:
        zv = "✗" if fs["zero_variance"] else ""
        md.append(f"| `{fs['feature']}` | {fs['monitor']} | {fs['mean']:.4f} | {fs['std']:.4f} | {fs['min']:.4f} | {fs['max']:.4f} | {zv} |")

    md.append("\n## 5. Exclusion Rules\n")
    md.append("- **Healing windows** (label='healing'): excluded from classifier evaluation")
    md.append("- **Unlabelled windows** (label='unlabeled' or label=''): excluded from classifier evaluation")
    md.append("- **Oct 3 raw data**: kept unlabelled until collection conditions verified by original collector")

    md.append("\n## 6. Train/Val/Test Separation Enforcement\n")
    md.append("- **Training**: model fitting and feature preprocessing (scalers fitted here only)")
    md.append("- **Validation**: hyperparameter selection, threshold calibration, model selection")
    md.append("- **Final test**: one-time evaluation of frozen pipeline. No test-set information may influence model or threshold selection.")

    # Write report
    report_path = os.path.join(args.out_dir, "dataset_audit.md")
    with open(report_path, "w") as f:
        f.write("\n".join(md) + "\n")

    # Write JSON
    audit_json = {
        "dataset": args.dataset,
        "total_windows": n_total,
        "supervised_windows": n_supervised,
        "label_counts": dict(label_counts),
        "supervised_class_counts": dict(sup_classes),
        "run_id_summary": {k: {"count": v["count"],
                                "labels": sorted(v["label"]),
                                "attack_classes": sorted(v["attack_class"])}
                           for k, v in run_id_info.items()},
        "total_features": len(feature_names),
        "zero_variance_features": [{"feature": f, "constant_value": v} for f, v in zero_var],
        "effective_features": n_effective,
        "feature_stats": feature_stats,
        "status": "PRELIMINARY",
    }
    json_path = os.path.join(args.out_dir, "dataset_audit.json")
    with open(json_path, "w") as f:
        json.dump(audit_json, f, indent=2)

    print(f"Dataset audit written to {report_path} and {json_path}")
    print(f"  Total: {n_total}, Supervised: {n_supervised}, Effective features: {n_effective}")
    print(f"  Zero-variance features: {len(zero_var)}")
    return audit_json

if __name__ == "__main__":
    main()
